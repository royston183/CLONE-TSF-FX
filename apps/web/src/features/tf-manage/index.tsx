import './tf-manage.overrides.css'
// Night mode. Generated from the sheet above by tools/gen-dark-css.mjs; it only restates the
// colours that change, at a higher specificity, so it must be imported after it.
import './tf-manage.dark.css'

const TABS = [
  { id: 'basicData', label: 'Basic Data', sections: BASIC_SECTIONS, fields: BASIC_FIELDS },
  {
    id: 'shippingData',
    label: 'Shipping Data',
    sections: SHIPPING_SECTIONS,
    fields: SHIPPING_FIELDS,
  },
  {
    id: 'purchSalesData',
    label: 'Purch-Sales Data',
    sections: PURCH_SALES_SECTIONS,
    fields: PURCH_SALES_FIELDS,
  },
  { id: 'statusTab', label: 'Status', sections: STATUS_SECTIONS, fields: STATUS_FIELDS },
] as const

/** Not a form tab. BL Data 1 renders the BL grid (BlDetailsPanel). */
const DEFERRED_TABS = [{ id: 'blData1', label: 'BL Data 1' }] as const

type TabId = (typeof TABS)[number]['id'] | (typeof DEFERRED_TABS)[number]['id']

/** The mark the legacy header carries, declared locally as the other converted apps do. */
const BRAND_LOGO =
  'https://raw.githubusercontent.com/ryannayak/fs-assets/e82f35a83e28689167b22b4300d4994a249acee0/fs-short-logo.png'

/** ApiError already carries the backend's own message; anything else is stringified. */
function errorText(err: unknown): string {
  return err instanceof Error ? err.message : String(err)
}

/** Tab order on screen matches the legacy bar, which interleaves the deferred BL Data 1 tab. */
const TAB_ORDER: ReadonlyArray<{ id: TabId; label: string }> = [
  { id: 'basicData', label: 'Basic Data' },
  { id: 'shippingData', label: 'Shipping Data' },
  { id: 'purchSalesData', label: 'Purch-Sales Data' },
  { id: 'blData1', label: 'BL Data 1' },
  { id: 'statusTab', label: 'Status' },
]

export default function TfManageApp() {
  const [rows, setRows] = useState<TrdFlowRow[]>([])
  const [filters, setFilters] = useState<TfFilters>(EMPTY_FILTERS)
  const [showFilters, setShowFilters] = useState(false)
  const [keyDate, setKeyDate] = useState('')
  const [selected, setSelected] = useState<TrdFlowRow | null>(null)
  const [draft, setDraft] = useState<TrdFlowRow>({})
  const [tab, setTab] = useState<TabId>('basicData')
  const [error, setError] = useState<string>()
  const [busy, setBusy] = useState(false)
  const [saved, setSaved] = useState(false)
  // Committed Deal ID assignments from BL Data 1's Assign Deal ID popup, keyed by
  // dealAssignmentKey. Held here (rather than on the row) since there is no OData entity yet.
  const [blDealAssignments, setBlDealAssignments] = useState<Record<string, string>>({})
  const [pendingBlAssignment, setPendingBlAssignment] = useState<PendingBlAssignment | null>(null)
  const [blReloadToken, setBlReloadToken] = useState(0)
  // BL Data 1's pending BL work (created / split / edited rows), written by Update. Takes the
  // Deal IDs this Update assigns to rows not stored yet, which go into their inserts. Resolves
  // to each created row's own id alongside the BL number the range issued it.
  const blSave = useRef<
    ((dealsForUnsaved: ReadonlyMap<string, string>, details?: BlInvoiceDetails) => Promise<Array<{ localId: string; blNo: string }> | null>) | null
  >(null)
  const registerBlSave = useCallback(
    (
      save:
        | ((dealsForUnsaved: ReadonlyMap<string, string>, details?: BlInvoiceDetails) => Promise<Array<{ localId: string; blNo: string }> | null>)
        | null,
    ) => {
      blSave.current = save
    },
    [],
  )
  const [blNotice, setBlNotice] = useState('')
  const [dealSuccessMessage, setDealSuccessMessage] = useState('')
  // Masters for the form tabs, read once. Each degrades to empty on its own (see masters.ts).
  const tfStatus = useAsync((signal) => loadTfStatusMaster(signal), [])
  const commodities = useAsync((signal) => loadCommodityMaster(signal), [])
  // Status tab's OTTK No / DTTK No / Deal ID selects: the same live masters the OTTK, DTTK and
  // Deal ID consoles themselves read from, not values scraped from whatever trade flows loaded.
  const ottkTickets = useAsync((signal) => loadOttk(signal).catch(() => []), [])
  const dttkTickets = useAsync((signal) => loadDttk(signal).catch(() => []), [])
  const dealMaster = useAsync((signal) => loadDealMaster(signal).catch(() => undefined), [])

  /** Distinct non-blank values, in source order, each offered once. */
  function uniqueOptions(values: readonly string[]): SelectOption[] {
    const seen = new Set<string>()
    const out: SelectOption[] = []
    for (const value of values) {
      const trimmed = value.trim()
      if (!trimmed || seen.has(trimmed)) continue
      seen.add(trimmed)
      out.push({ value: trimmed, label: trimmed })
    }
    return out.sort((a, b) => a.value.localeCompare(b.value))
  }

  /** A master's codes where the field has one; otherwise the values the loaded rows carry. */
  function optionsFor(field: keyof TrdFlowRow): readonly SelectOption[] {
    if (field === 'ZogbsStatId') return tfStatus.data?.ogbs ?? []
    if (field === 'ZflwCod1') return tfStatus.data?.flow ?? []
    if (field === 'ZflwCod2') return tfStatus.data?.blocked ?? []
    if (field === 'ZtfType') return TF_TYPE_OPTIONS
    // GT Commodity: ZSGTSFTR_COMODIT's own commodity codes, not just whichever ones happen to
    // appear among the trade flows already loaded.
    if (field === 'ZtrmComId') {
      return (commodities.data ?? []).map((c) => {
        const value = String(c.ZcomId ?? '').trim()
        const desc = String(c.ZcomDesc ?? c.ZcomSdesc ?? '').trim()
        return { value, label: desc ? `${value} ${desc}` : value }
      }).filter((o) => o.value)
    }
    if (field === 'ZottkNo') return uniqueOptions((ottkTickets.data ?? []).map((r) => String(r.ZottkNo ?? '')))
    if (field === 'ZdttkNo') return uniqueOptions((dttkTickets.data ?? []).map((r) => String(r.ZdttkNo ?? '')))
    if (field === 'ZdealId') return uniqueOptions((dealMaster.data?.deals ?? []).map((d) => d.dealId))
    return distinctValues(rows, field).map((value) => ({ value, label: value }))
  }

  useEffect(() => {
    void refresh()
  }, [])

  async function refresh() {
    setError(undefined)
    setBusy(true)
    try {
      setRows(await loadTradeFlows())
    } catch (err) {
      setError(errorText(err))
    } finally {
      setBusy(false)
    }
  }

  function select(row: TrdFlowRow) {
    setSelected(row)
    // Some trade flows are stored with CPMT Amount still 0 even though Quantity and Current
    // Market Price are both present — it was never computed upstream. Filled in here so what's
    // shown on open matches the formula; Contract Amount and every other field stay as stored.
    setDraft(withCpmtAmount({ ...row }))
    setSaved(false)
    setBlNotice('')
    setError(undefined)
    setDealSuccessMessage('')
  }

  async function save() {
    if (!selected) return
    const key = rowKey(selected)
    if (!key) {
      setError('This row has no Trade Flow ID and split, so it cannot be updated.')
      return
    }
    // BL Data 1's Assign Deal ID popup only stages the assignment; Update is what commits it,
    // the same way the legacy prototype's handleWsUpdate always applied a pending assignment
    // regardless of which tab was open when clicked.
    const pending =
      pendingBlAssignment && pendingBlAssignment.tfKey.ZtfNo === key.ZtfNo && pendingBlAssignment.tfKey.ZtfSplit === key.ZtfSplit
        ? pendingBlAssignment
        : null
    // Checked against the TF's own Quantity, not any one BL's — several line items can be
    // assigned the same Deal ID in one operation, so it is their combined Quantity that must
    // not exceed it.
    if (pending && pending.totalQuantity > (Number(selected.Zquantity) || 0)) {
      setError('Total quantity is more than the TF quantity')
      return
    }
    if (pending) {
      setError(undefined)
      setBusy(true)
      try {
        // Check again before any BL write, including new/split BL inserts. The MC may have
        // changed since Assign was pressed; compliance exceptions do not waive this rule.
        await validateAssignmentCommodity(pending.dealId, pending.details.ZtrmComId)
      } catch (err) {
        setError(errorText(err))
        return
      } finally {
        setBusy(false)
      }
    }
    // A target the grid holds but ZSGTSFTR_BL does not (Create BL, BL Split) has no stored key
    // to update, and a Create BL row has no BL ID at all until its insert draws one from the
    // SNRO range. So its Deal ID goes into that insert; only stored rows are assigned by key.
    const unsavedTargets = pending?.targets.filter((target) => isUnsavedBl(target.blId)) ?? []
    const storedTargets = pending?.targets.filter((target) => !isUnsavedBl(target.blId)) ?? []
    const dealsForUnsaved = new Map(unsavedTargets.map((target) => [target.blId, pending?.dealId ?? '']))
    // An unsaved target has no BL number yet — filled in once its insert below issues one — so
    // the success popup can still name it rather than leaving it out of "BL: ...".
    let issuedByLocalId = new Map<string, string>()

    // First BL Data 1's own changes: created and split rows are inserted (issuing BL IDs),
    // edited cells updated.
    if ((tab === 'blData1' || dealsForUnsaved.size > 0) && blSave.current) {
      setError(undefined)
      setBusy(true)
      try {
        const issued = await blSave.current(dealsForUnsaved, pending?.details)
        if (issued) {
          issuedByLocalId = new Map(issued.map((i) => [i.localId, i.blNo]))
          setBlNotice(issued.length ? `Saved. New BL ID(s): ${issued.map((i) => i.blNo).join(', ')}` : 'BL changes saved.')
          setBlReloadToken((token) => token + 1)
        }
        setSaved(true)
      } catch (err) {
        // The rows stay on screen, so nothing is lost and Update can be pressed again.
        setError(errorText(err))
        return
      } finally {
        setBusy(false)
      }
    }

    // Then the Deal ID on rows that were already stored.
    if (pending) {
      setError(undefined)
      setBusy(true)
      try {
        // Written to ZSGTSFTR_BL before the grid shows it, so what is on screen is what is stored.
        for (const target of storedTargets) {
          await assignBlDeal(pending.tfKey, target.bl, pending.dealId, pending.details)
        }
        // Every BL, stored and just inserted, now carries the Deal ID: only then does the Deal ID
        // move to 04, as BL_UPDATE does after its BL writes.
        await markDealAssigned(pending.dealId)
        setBlDealAssignments((current) => {
          const next = { ...current }
          for (const target of storedTargets) next[dealAssignmentKey(pending.tfKey, target.blId)] = pending.dealId
          return next
        })
        setPendingBlAssignment(null)
        setBlReloadToken((token) => token + 1)
        setSaved(true)
      } catch (err) {
        // The unsaved targets were inserted with their Deal ID above, so only the stored ones
        // stay pending, and Update can simply be pressed again (the BL writes and the 04 update
        // are both idempotent).
        setPendingBlAssignment({ ...pending, targets: storedTargets })
        setError(errorText(err))
        return
      } finally {
        setBusy(false)
      }
    }

    // Reached only once every targeted BL — stored and just-inserted alike — is confirmed
    // written, so the popup never claims an assignment that a caught error above stopped short.
    if (pending) {
      const assignedBlNumbers = pending.targets
        .map((target) => (isUnsavedBl(target.blId) ? issuedByLocalId.get(target.blId) ?? '' : target.bl.ZblNo))
        .filter((blNo) => blNo.trim() !== '')
      if (assignedBlNumbers.length > 0) {
        setDealSuccessMessage(`Deal ID assigned successfully to BL: ${assignedBlNumbers.join(', ')}`)
      }
    }

    const active = TABS.find((t) => t.id === tab)
    if (!active) return

    // Only the current tab's mapped fields are sent; an unmapped control has no field.
    const changes: Partial<TrdFlowRow> = {}
    for (const descriptor of active.fields) {
      const field = descriptor.field
      if (!field) continue
      if (draft[field] !== selected[field]) {
        Object.assign(changes, { [field]: draft[field] })
      }
    }
    // SAP keeps each status's text beside its code (SE11: ZOGBS_STAT_DESC, ZFLW_STAS1, ZFLW_STAS2);
    // the text goes with the code, from the master, so the two cannot disagree.
    const nameOf = (code: unknown) => tfStatus.data?.nameOf.get(String(code ?? '')) ?? ''
    if (changes.ZogbsStatId !== undefined) changes.ZogbsStatDesc = nameOf(changes.ZogbsStatId)
    if (changes.ZflwCod1 !== undefined) changes.ZflwStas1 = nameOf(changes.ZflwCod1)
    if (changes.ZflwCod2 !== undefined) changes.ZflwStas2 = nameOf(changes.ZflwCod2)
    if (changes.ZtrmComId !== undefined) {
      const commodity = commodities.data?.find((row) => String(row.ZcomId ?? '').trim() === changes.ZtrmComId)
      changes.ZtrmComDesc = String(commodity?.ZcomDesc ?? commodity?.ZcomSdesc ?? '').trim()
    }
    if (Object.keys(changes).length === 0) {
      setSaved(true)
      return
    }

    setError(undefined)
    setBusy(true)
    try {
      await patchTradeFlow(key, changes)
      // Keep the edited values on screen and fold them into the list, with the audit stamps the
      // middleware just wrote (they are set server-side, so only a re-read has them).
      const stored = await reloadTradeFlow(key)
      const audit: Partial<TrdFlowRow> = {}
      for (const field of ['ZchangedBy', 'ZchangedDate', 'ZchangedTime'] as const) {
        const value = stored?.[field]
        if (value !== undefined) audit[field] = value
      }
      const merged = { ...selected, ...changes, ...audit }
      setSelected(merged)
      setDraft((current) => ({ ...current, ...audit }))
      setRows((current) =>
        current.map((row) => {
          const candidate = rowKey(row)
          return candidate && candidate.ZtfNo === key.ZtfNo && candidate.ZtfSplit === key.ZtfSplit
            ? merged
            : row
        }),
      )
      setSaved(true)
    } catch (err) {
      // The draft is deliberately left untouched so nothing typed is lost.
      setError(errorText(err))
    } finally {
      setBusy(false)
    }
  }

  const activeTab = TABS.find((t) => t.id === tab)

  return (
    <div className="tfmanage">
      <div className="app-shell">
        <header className="app-header">
          <div className="ds-header-left">
            <BackButton className="hdr-btn" />
            <img className="ds-mark" alt="Fourth Signal" src={BRAND_LOGO} />
            <div className="app-title">Manage Trade Flows</div>
          </div>
          <div className="ds-header-right">
            <span className="ds-conn" title="System connected" />
            <button
              type="button"
              className="hdr-btn"
              id="btnRefresh"
              onClick={() => void refresh()}
              disabled={busy}
            >
              {busy ? 'Working…' : '↻ Refresh'}
            </button>
            <SignOutButton className="hdr-btn" />
          </div>
        </header>

        <main className="screen" id="screenMain">
          {error ? (
            <div className="ds-panel" role="alert">
              <div className="section-body">
                <span className="field-hint">{error}</span>
              </div>
            </div>
          ) : null}

          <TfTable
            rows={rows}
            filters={filters}
            onFiltersChange={setFilters}
            showFilters={showFilters}
            onToggleFilters={() => setShowFilters((on) => !on)}
            onClearFilters={() => setFilters(EMPTY_FILTERS)}
            keyDate={keyDate}
            onKeyDateChange={setKeyDate}
            selected={selected}
            onSelect={select}
            filterOptions={{
              ZflwCod1: tfStatus.data?.flow ?? [],
              ZogbsStatId: tfStatus.data?.ogbs ?? [],
              ZflwCod2: tfStatus.data?.blocked ?? [],
            }}
          />

          {selected ? (
            <div
              className="screen"
              id="screenWorkspace"
              role="dialog"
              aria-modal="true"
              aria-labelledby="wsModalTitle"
              onClick={(event) => {
                if (event.target === event.currentTarget) setSelected(null)
              }}
            >
              <section className="ws-modal-box">
                <div className="modal-head ws-modal-head">
                  <div className="modal-heading">
                    <span className="modal-title" id="wsModalTitle">
                      Trade Flow {selected.ZtfNo} / {selected.ZtfSplit}
                    </span>
                    <span className="ws-modal-sub">Manage Trade Flows · Detail</span>
                  </div>
                  <button
                    type="button"
                    className="modal-close-btn"
                    aria-label="Close"
                    onClick={() => setSelected(null)}
                  >
                    ×
                  </button>
                </div>

                <div className="ws-modal-body">
                  <div className="tab-bar" id="wsTabBar">
                    {TAB_ORDER.map((t) => (
                      <button
                        key={t.id}
                        type="button"
                        className={tab === t.id ? 'tab-btn active' : 'tab-btn'}
                        onClick={() => setTab(t.id)}
                      >
                        {t.label}
                      </button>
                    ))}
                  </div>

                  <div className="tab-panel">
                    {activeTab ? (
                      <div className="tab-content" id={`tabPanel-${activeTab.id}`}>
                        {activeTab.sections.map((section) => (
                          <FieldGrid
                            key={section.heading}
                            section={section}
                            draft={draft}
                            optionsFor={optionsFor}
                            derivedValue={(id) => (id === 'bdBuCommodity' ? buCommodity(draft, commodities.data ?? []) : '')}
                            onChange={(field, value) => {
                              setDraft((current) => withDerivedFields({ ...current, [field]: value }, field))
                              setSaved(false)
                            }}
                          />
                        ))}
                      </div>
                    ) : tab === 'blData1' && rowKey(selected) ? (
                      <BlDetailsPanel
                        key={`${selected.ZtfNo}-${selected.ZtfSplit}`}
                        tfKey={rowKey(selected)!}
                        tfQuantity={selected.Zquantity}
                        tfCommodity={selected.Zcmmd}
                        tfBlNumber={selected.Zblno}
                        tradeFlow={selected}
                        dealAssignments={blDealAssignments}
                        pendingAssignment={pendingBlAssignment}
                        onPendingAssignmentChange={setPendingBlAssignment}
                        reloadToken={blReloadToken}
                        registerSave={registerBlSave}
                      />
                    ) : (
                      <div className="tab-content" id={`tabPanel-${tab}`}>
                        <div className="section-box">
                          <div className="section-head">Not yet backed by SAP</div>
                          <div className="section-body">
                            <span className="field-hint">
                              BL line items, deal assignment and compliance have no OData entity yet,
                              so this tab is deferred to Stage 2 rather than run on placeholder data.
                            </span>
                          </div>
                        </div>
                      </div>
                    )}
                  </div>
                </div>

                <div className="modal-footer">
                  {/* An Update that fails is reported here too: the page's own banner sits behind the popup. */}
                  {error ? (
                    <span className="field-hint modal-error" role="alert">
                      {error}
                    </span>
                  ) : (
                    <span className="field-hint">{saved ? blNotice || 'Saved.' : ''}</span>
                  )}
                  <div className="modal-actions">
                    <button
                      type="button"
                      className="hdr-btn"
                      onClick={() => setSelected(null)}
                      disabled={busy}
                    >
                      Cancel
                    </button>
                    <button
                      type="button"
                      className="hdr-btn primary"
                      onClick={() => void save()}
                      disabled={busy || (!activeTab && tab !== 'blData1' && !pendingBlAssignment)}
                    >
                      Update
                    </button>
                  </div>
                </div>
              </section>
            </div>
          ) : null}
        </main>
      </div>
      <DealSuccessModal message={dealSuccessMessage} onClose={() => setDealSuccessMessage('')} />
    </div>
  )
}
